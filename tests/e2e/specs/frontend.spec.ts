test('action errors, disabled updates, and narrow-screen navigation remain usable',async({page,request},info)=>{
 const state=await(await request.get(`${api}/test/state`)).json()
 const updateRequests:(string|null)[]=[]
 page.on('request',request=>{if(new URL(request.url()).pathname==='/api/update'&&request.method()==='POST')updateRequests.push(request.postData())})
 await page.setViewportSize({width:320,height:800})
 await page.goto('/')
 await page.getByRole('button',{name:'Open navigation'}).click()
 await page.locator('.mobile-nav').getByRole('link',{name:'Stacks'}).click()
 await expect(page.locator('.navigation-drawer')).toBeHidden()
 await expect(page.locator('[data-stack]')).toHaveCount(6)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
 await capture(page,info,'06-mobile-stacks')
 await page.goto('/stacks?view=grid')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
 await page.getByRole('searchbox').fill('does-not-exist')
 await expect(page.getByText('No matching stacks. Change search or filters to see more.')).toBeVisible()
 await page.goto('/operations')
 await control(request,'configure',{updateStatus:503})
 const updateAll=page.getByRole('button',{name:'Update all stacks…',exact:true})
 await updateAll.click()
 const impact=page.getByRole('dialog',{name:'Update all stacks',exact:true})
 await expect(impact).toContainText('All stacks on this instance, regardless of inventory filters or the current page')
 await expect(impact).toContainText('Host-wide prune:')
 await expect(impact).toContainText('including images outside managed stacks')
 expect(updateRequests).toHaveLength(0)
 await impact.getByRole('button',{name:'Cancel',exact:true}).click()
 await expect(impact).toBeHidden()
 expect(updateRequests).toHaveLength(0)
 await updateAll.click()
 const rejectedUpdate=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/update'&&response.request().method()==='POST')
 await impact.getByRole('button',{name:'Update all stacks and prune images',exact:true}).click()
 expect((await rejectedUpdate).status()).toBe(503)
  await expect(page.getByRole('alert').filter({hasText:'Request outcome unknown; it may still be running'})).toBeVisible()
 await expect(updateAll).toBeDisabled()
 expect(updateRequests).toEqual([null])
 await control(request,'configure',{instance:{...state.instance,schedule:{...state.instance.schedule,enabled:false},capabilities:{...state.instance.capabilities,imageUpdates:false}}})
 await page.reload()
 await expect(page.getByRole('button',{name:'Update all stacks…',exact:true})).toBeDisabled()
 await expect(page.getByText('Image updates disabled by instance configuration',{exact:false})).toBeVisible()
 await expect(page.getByText('Scheduled updates disabled')).toBeVisible()
})
