import { expect, test, type APIRequestContext, type Page, type TestInfo } from '@playwright/test'
const api='http://127.0.0.1:18082'
async function control(request:APIRequestContext,path:string,data?:unknown){const response=await request.post(`${api}/test/${path}`,{data});expect(response.ok()).toBeTruthy()}
async function capture(page:Page,info:TestInfo,name:string){await page.evaluate(()=>document.fonts.ready);const path=info.outputPath(`${name}.png`);await page.screenshot({path,fullPage:true,animations:'disabled'});await info.attach(name,{path,contentType:'image/png'})}
test.beforeEach(async({request})=>{await control(request,'reset')})

